def render_variables_stylesheet() -> str:
    stack = wrap_font_stack(font_stack(None, BASE_UI_FACES), "\t\t")
    body = ROOT_VARIABLES_TEMPLATE.format(sans=stack)
    return "\n".join([SPDX_CSS_HEADER, GENERATED_CSS_HEADER, "", body])


def render_locale_fallbacks_stylesheet() -> str:
    lines = [SPDX_CSS_HEADER, GENERATED_CSS_HEADER, "", LOCALE_FALLBACKS_COMMENT]
    for langs, preferred, os_faces in LOCALE_FALLBACKS:
        selector = ",\n".join(f":root:lang({lang})" for lang in langs)
        stack = wrap_font_stack(font_stack(preferred, os_faces), "\t\t")
        lines.append(f"{selector} {{\n\t--font-sans:\n\t\t{stack};\n}}")
    return "\n".join([*lines, ""])


def _http_get(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "fluxer-font-build"})
    with urllib.request.urlopen(request) as response:  # noqa: S310 - pinned https URLs
        return response.read()


def _check_integrity(integrity: str, blob: bytes, label: str) -> None:
    algo, _, encoded = integrity.partition("-")
    actual = base64.b64encode(hashlib.new(algo, blob).digest()).decode()
    if actual != encoded:
        raise SystemExit(f"integrity mismatch for {label}: expected {encoded}, got {actual}")


def _extract_tar(blob: bytes, root: Path) -> None:
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)
    with tarfile.open(fileobj=io.BytesIO(blob), mode="r:gz") as archive:
        for member in archive.getmembers():
            _extract_member(archive, member, member.name, root, member.isdir())


def _extract_zip(blob: bytes, root: Path) -> None:
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)
    with zipfile.ZipFile(io.BytesIO(blob)) as archive:
        for info in archive.infolist():
            _extract_member(archive, info, info.filename, root, info.is_dir())


def _extract_member(archive: object, member: object, name: str, root: Path, is_dir: bool) -> None:
    dest = (root / name).resolve()
    if not str(dest).startswith(str(root.resolve())):
        raise SystemExit(f"refusing to extract outside the cache: {name}")
    if is_dir:
        dest.mkdir(parents=True, exist_ok=True)
        return
    dest.parent.mkdir(parents=True, exist_ok=True)
    reader = (
        archive.extractfile(member)
        if isinstance(archive, tarfile.TarFile)
        else archive.open(member)
    )
    if reader is None:
        return
    with reader:
        dest.write_bytes(reader.read())


def fluxer_name(value: str) -> str:
    return value.replace("IBM Plex ", "Fluxer ").replace("IBMPlex", "Fluxer")


def _name_map(font: TTFont) -> dict[tuple[int, int, int, int], str]:
    return {
        (r.nameID, r.platformID, r.platEncID, r.langID): r.toUnicode() for r in font["name"].names
    }


def build_font(src: Path, gasp: dict[int, int]) -> bytes:
    font = TTFont(src, lazy=True, recalcTimestamp=False, recalcBBoxes=False)
    font["gasp"].gaspRange = dict(gasp)
    for record in font["name"].names:
        if record.nameID in RENAME_NAME_IDS:
            record.string = fluxer_name(record.toUnicode())
    font.flavor = "woff2"
    buffer = io.BytesIO()
    font.save(buffer)
    font.close()
    return buffer.getvalue()


def check_rebuild(src: Path, produced: bytes, gasp: dict[int, int]) -> None:
    upstream = TTFont(src, lazy=True)
    built = TTFont(io.BytesIO(produced), lazy=True)
    try:
        up_tags = {t for t in upstream.keys() if t != "GlyphOrder"}
        new_tags = {t for t in built.keys() if t != "GlyphOrder"}
        if up_tags != new_tags:
            raise SystemExit(
                f"{src.name}: table set changed: "
                f"+{sorted(new_tags - up_tags)} -{sorted(up_tags - new_tags)}"
            )
        for tag in sorted(up_tags - MUTABLE_TABLES):
            if upstream.reader[tag] != built.reader[tag]:
                raise SystemExit(f"{src.name}: table {tag!r} changed but must not")
        for tag in CRITICAL_TABLES:
            if tag in up_tags and upstream.reader[tag] != built.reader[tag]:
                raise SystemExit(f"{src.name}: critical table {tag!r} changed")

        up_head = upstream.reader["head"]
        new_head = built.reader["head"]
        if len(up_head) != len(new_head):
            raise SystemExit(f"{src.name}: head length changed")
        if (
            up_head[: HEAD_CHECKSUM_SLICE.start] != new_head[: HEAD_CHECKSUM_SLICE.start]
            or up_head[HEAD_CHECKSUM_SLICE.stop :] != new_head[HEAD_CHECKSUM_SLICE.stop :]
        ):
            raise SystemExit(f"{src.name}: head changed outside checkSumAdjustment")

        if built["gasp"].gaspRange != gasp:
            raise SystemExit(f"{src.name}: gasp is {built['gasp'].gaspRange}, expected {gasp}")
        if built["gasp"].version != 1:
            raise SystemExit(f"{src.name}: gasp version is {built['gasp'].version}, expected 1")

        up_names = _name_map(upstream)
        new_names = _name_map(built)
        if set(up_names) != set(new_names):
            raise SystemExit(f"{src.name}: name record set changed")
        for key, value in up_names.items():
            expected = fluxer_name(value) if key[0] in RENAME_NAME_IDS else value
            if new_names[key] != expected:
                raise SystemExit(
                    f"{src.name}: name {key} is {new_names[key]!r}, expected {expected!r}"
                )
        check_no_reserved_name(built, src.name)
    finally:
        upstream.close()
        built.close()


def check_no_reserved_name(font: TTFont, label: str) -> None:
    for record in font["name"].names:
        if record.nameID in NO_PLEX_NAME_IDS and "Plex" in record.toUnicode():
            raise SystemExit(
                f"{label}: reserved font name 'Plex' still present in name ID {record.nameID}"
            )


def subset_options() -> SubsetOptions:
    options = SubsetOptions()
    options.hinting = True  # keep glyph instructions; fpgm/prep/cvt pass through
    options.legacy_kern = True
    options.layout_features = ["*"]  # CJK needs vert/vrt2/halt/palt/trad/smpl
    options.layout_scripts = ["*"]
    options.name_IDs = ["*"]  # the OFL rename lives in the name table
    options.name_legacy = True
    options.name_languages = ["*"]
    options.notdef_outline = True
    options.glyph_names = False  # post 3.0; names are not rendering data
    options.recalc_bounds = False  # keep upstream head/glyf bounding boxes
    options.recalc_timestamp = False  # keep upstream head.modified
    options.recalc_max_context = False
    options.recalc_average_width = False  # keep OS/2.xAvgCharWidth
    options.prune_unicode_ranges = False  # keep OS/2.ulUnicodeRange
    options.prune_codepage_ranges = False
    options.drop_tables = []
    options.passthrough_tables = True  # e.g. `meta`, which the subsetter cannot slice
    options.ignore_missing_unicodes = True
    return options


def subset_face(sfnt: bytes, codepoints: tuple[int, ...]) -> bytes:
    font = TTFont(io.BytesIO(sfnt), lazy=True, recalcTimestamp=False, recalcBBoxes=False)
    subsetter = Subsetter(options=subset_options())
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.flavor = "woff2"
    buffer = io.BytesIO()
    font.save(buffer)
    font.close()
    return buffer.getvalue()


def glyph_signature(glyph_set: object, glyf: object, name: str) -> tuple:
    pen = DecomposingRecordingPen(glyph_set)
    glyph_set[name].draw(pen)
    glyph = glyf[name]
    program = getattr(glyph, "program", None)
    bytecode = bytes(program.getBytecode()) if program is not None else b""
    box = (glyph.xMin, glyph.yMin, glyph.xMax, glyph.yMax) if glyph.numberOfContours != 0 else ()
    return (tuple(pen.value), box, bytecode)


def metric_signature(font: TTFont) -> dict[str, int]:
    values: dict[str, int] = {}
    for table, field_name in METRIC_FIELDS:
        if table not in font:
            continue
        value = getattr(font[table], field_name, None)
        if value is None:
            continue
        values[f"{table.strip()}.{field_name}"] = int(value)
    return values


def check_subset(
    parent: TTFont, chunk_bytes: bytes, requested: tuple[int, ...], label: str
) -> dict:
    chunk = TTFont(io.BytesIO(chunk_bytes), lazy=True)
    try:
        parent_tags = {t for t in parent.keys() if t != "GlyphOrder"}
        chunk_tags = {t for t in chunk.keys() if t != "GlyphOrder"}
        if parent_tags != chunk_tags:
            raise SystemExit(
                f"{label}: table set changed: "
                f"+{sorted(chunk_tags - parent_tags)} -{sorted(parent_tags - chunk_tags)}"
            )
        for tag in HINTING_TABLES + ("gasp",):
            if parent.reader[tag] != chunk.reader[tag]:
                raise SystemExit(f"{label}: table {tag!r} must pass through unchanged")
        if metric_signature(parent) != metric_signature(chunk):
            raise SystemExit(f"{label}: vertical metrics changed")
        check_no_reserved_name(chunk, label)
        if not (chunk["name"].getDebugName(6) or "").startswith("Fluxer"):
            raise SystemExit(f"{label}: PostScript name is not a Fluxer name")

        chunk_cmap = chunk.getBestCmap()
        expected = {cp for cp in requested if cp in parent.getBestCmap()}
        if set(chunk_cmap) != expected:
            missing = sorted(expected - set(chunk_cmap))[:4]
            extra = sorted(set(chunk_cmap) - expected)[:4]
            raise SystemExit(f"{label}: cmap drifted from the plan (-{missing} +{extra})")

        parent_cmap = parent.getBestCmap()
        parent_glyf = parent["glyf"]
        chunk_glyf = chunk["glyf"]
        parent_set = parent.getGlyphSet()
        chunk_set = chunk.getGlyphSet()
        parent_hmtx = parent["hmtx"]
        chunk_hmtx = chunk["hmtx"]
        parent_vmtx = parent["vmtx"] if "vmtx" in parent else None
        chunk_vmtx = chunk["vmtx"] if "vmtx" in chunk else None
        for cp in sorted(expected):
            name = parent_cmap[cp]
            chunk_name = chunk_cmap[cp]
            if glyph_signature(parent_set, parent_glyf, name) != glyph_signature(
                chunk_set, chunk_glyf, chunk_name
            ):
                raise SystemExit(f"{label}: outline changed for U+{cp:04X} ({name})")
            if parent_hmtx[name] != chunk_hmtx[chunk_name]:
                raise SystemExit(f"{label}: horizontal metrics changed for U+{cp:04X} ({name})")
            if parent_vmtx is not None and parent_vmtx[name] != chunk_vmtx[chunk_name]:
                raise SystemExit(f"{label}: vertical metrics changed for U+{cp:04X} ({name})")
        return {
            "codepoints": sorted(chunk_cmap),
            "hinting": {tag: len(chunk.reader[tag]) for tag in HINTING_TABLES},
            "metrics": metric_signature(chunk),
        }
    finally:
        chunk.close()


def plan_chunks(codepoints: set[int], target: int) -> list[tuple[int, ...]]:
    if target < 1:
        raise SystemExit(f"chunk target must be positive, got {target}")
    by_block: dict[str, list[int]] = {}
    for cp in sorted(codepoints):
        by_block.setdefault(ftunicodedata.block(cp), []).append(cp)

    chunks: list[tuple[int, ...]] = []
    pending: list[int] = []

    def flush() -> None:
        if pending:
            chunks.append(tuple(pending))
            pending.clear()

    for _, members in sorted(by_block.items(), key=lambda item: item[1][0]):
        if len(members) < MIN_STANDALONE_BLOCK:
            pending.extend(members)
            if len(pending) >= target:
                flush()
            continue
        flush()
        parts = max(1, round(len(members) / target)) if len(members) > target else 1
        size = -(-len(members) // parts)
        for start in range(0, len(members), size):
            chunks.append(tuple(members[start : start + size]))
    flush()
    if not chunks:
        raise SystemExit("chunk plan is empty")
    return chunks


