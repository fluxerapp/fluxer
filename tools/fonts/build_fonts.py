def font_stack(preferred: str | None, os_faces: tuple[str, ...]) -> list[str]:
    scripts = [preferred] if preferred else []
    scripts += [family for family in SCRIPT_FAMILY_ORDER if family != preferred]
    return [
        quote_family("Fluxer Sans"),
        *(quote_family(family) for family in scripts),
        *GENERIC_UI_FACES,
        *(quote_family(face) for face in os_faces),
        "sans-serif",
    ]


def quote_family(name: str) -> str:
    return f"'{name}'"


def wrap_font_stack(entries: list[str], indent: str, width: int = 118) -> str:
    lines: list[str] = []
    current = ""
    for index, entry in enumerate(entries):
        piece = entry if index == len(entries) - 1 else f"{entry},"
        candidate = f"{current} {piece}" if current else piece
        if current and len(indent) + len(candidate) > width:
            lines.append(current)
            current = piece
        else:
            current = candidate
    if current:
        lines.append(current)
    return f"\n{indent}".join(lines)


