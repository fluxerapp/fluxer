def css_weight(weight: str) -> int:
    upright = (
        weight[: -len("Italic")] if weight.endswith("Italic") and weight != "Italic" else weight
    )
    if upright == "Italic":
        upright = "Regular"
    return CSS_WEIGHTS[upright]


def css_style(weight: str) -> str:
    return "italic" if weight.endswith("Italic") else "normal"


@dataclass(frozen=True)
class NpmSource:
    package: str
    version: str

    @property
    def label(self) -> str:
        return f"{self.package}@{self.version}"

    def provenance(self) -> dict[str, str]:
        return {"type": "npm", "package": self.package, "version": self.version}

    def fetch(self, cache: Path) -> Path:
        root = cache / f"npm-{self.package.replace('/', '-').lstrip('@')}-{self.version}"
        marker = root / ".complete"
        meta_url = f"https://registry.npmjs.org/{self.package}/{self.version}"
        if not marker.exists():
            meta = json.loads(_http_get(meta_url))
            tarball = _http_get(meta["dist"]["tarball"])
            _check_integrity(meta["dist"]["integrity"], tarball, self.label)
            _extract_tar(tarball, root)
            marker.write_text(hashlib.sha256(tarball).hexdigest() + "\n")
        return root / "package"

    def artifact_sha256(self, cache: Path) -> str:
        root = cache / f"npm-{self.package.replace('/', '-').lstrip('@')}-{self.version}"
        return (root / ".complete").read_text().strip()


@dataclass(frozen=True)
class GithubReleaseSource:
    repo: str
    tag: str
    asset: str

    @property
    def label(self) -> str:
        return f"{self.repo}@{self.tag}:{self.asset}"

    def provenance(self) -> dict[str, str]:
        return {
            "type": "github-release",
            "repo": self.repo,
            "tag": self.tag,
            "asset": self.asset,
        }

    def _root(self, cache: Path) -> Path:
        slug = re.sub(r"[^A-Za-z0-9]+", "-", f"{self.repo}-{self.tag}").strip("-")
        return cache / f"gh-{slug}"

    def fetch(self, cache: Path) -> Path:
        root = self._root(cache)
        marker = root / ".complete"
        if not marker.exists():
            url = (
                f"https://github.com/{self.repo}/releases/download/"
                f"{urllib.parse.quote(self.tag, safe='/')}/{self.asset}"
            )
            blob = _http_get(url)
            _extract_zip(blob, root)
            marker.write_text(hashlib.sha256(blob).hexdigest() + "\n")
        return root

    def artifact_sha256(self, cache: Path) -> str:
        return (self._root(cache) / ".complete").read_text().strip()


