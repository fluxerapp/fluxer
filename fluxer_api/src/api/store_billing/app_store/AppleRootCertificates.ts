let pinnedRoots: ReadonlyArray<X509Certificate> | null = null;
let injectedRoots: ReadonlyArray<X509Certificate> | undefined;

export function getAppleRootCertificates(): ReadonlyArray<X509Certificate> {
	if (injectedRoots !== undefined) {
		return injectedRoots;
	}
	pinnedRoots ??= [new X509Certificate(APPLE_ROOT_CA_G3_PEM)];
	return pinnedRoots;
}

export function setInjectedAppleRootCertificates(roots: ReadonlyArray<X509Certificate> | undefined): void {
	injectedRoots = roots;
}
