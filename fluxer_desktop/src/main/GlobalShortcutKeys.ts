export const MODIFIER_KEY_CODES = {
	ctrl: ['ControlLeft', 'ControlRight'],
	alt: ['AltLeft', 'AltRight'],
	shift: ['ShiftLeft', 'ShiftRight'],
	meta: ['MetaLeft', 'MetaRight'],
} as const;

export type ModifierKind = keyof typeof MODIFIER_KEY_CODES;

export function modifierKindForCode(code: string | null): ModifierKind | null {
	if (code === null) return null;
	for (const kind of Object.keys(MODIFIER_KEY_CODES) as Array<ModifierKind>) {
		if ((MODIFIER_KEY_CODES[kind] as ReadonlyArray<string>).includes(code)) return kind;
	}
	return null;
}

export function evdevKeyToDomCode(keycode: number): string | null {
	return EVDEV_KEY_CODES.get(keycode) ?? null;
}

export function x11KeycodeToDomCode(keycode: number): string | null {
	if (keycode < X11_KEYCODE_OFFSET) return null;
	return evdevKeyToDomCode(keycode - X11_KEYCODE_OFFSET);
}

export function windowsScanCodeKey(scanCode: number, extended: boolean): number {
	return extended ? WINDOWS_EXTENDED_SCAN_PREFIX | scanCode : scanCode;
}

export function windowsKeyToDomCode(scanCode: number, extended: boolean, virtualKey: number): string | null {
	const fromScanCode = scanCode === 0 ? undefined : WINDOWS_SCAN_CODES.get(windowsScanCodeKey(scanCode, extended));
	return fromScanCode ?? WINDOWS_VIRTUAL_KEY_CODES.get(virtualKey) ?? null;
}

