const XDG_KEYSYM_PATTERN = /^[A-Za-z0-9_]+$/;

function xdgKeysymForCombo(combo: {key: string; code?: string}): string | null {
	if (/^[a-z]$/i.test(combo.key) && !combo.code?.startsWith('Numpad')) return combo.key.toLowerCase();
	const code = combo.code ?? usLayoutKeyToDomCode(combo.key);
	if (code === null) return null;
	const keysym = XDG_CODE_KEYSYMS.get(code) ?? null;
	return keysym !== null && XDG_KEYSYM_PATTERN.test(keysym) ? keysym : null;
}

export interface XdgTriggerCombo {
	key: string;
	code?: string;
	ctrl: boolean;
	alt: boolean;
	shift: boolean;
	meta: boolean;
	mouseButton?: number;
	modifierOnly?: boolean;
	bothSides?: boolean;
}

export function comboToXdgTrigger(combo: XdgTriggerCombo): string | null {
	if (combo.mouseButton !== undefined || combo.modifierOnly || combo.bothSides) return null;
	const keysym = xdgKeysymForCombo(combo);
	if (keysym === null) return null;
	const parts: Array<string> = [];
	if (combo.ctrl) parts.push('CTRL');
	if (combo.alt) parts.push('ALT');
	if (combo.shift) parts.push('SHIFT');
	if (combo.meta) parts.push('LOGO');
	parts.push(keysym);
	return parts.join('+');
}
